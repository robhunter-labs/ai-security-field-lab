#!/usr/bin/env python3
"""build_catalog.py - render catalog/classes.json to catalog/NON_UNIQUE_CLASSES.md.

classes.json is the single source of truth; the Markdown is generated.
  python3 catalog/build_catalog.py           # write the Markdown
  python3 catalog/build_catalog.py --check   # exit 1 if the Markdown is stale or the data is inconsistent
Standard library only.
"""
import json
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
DATA = os.path.join(HERE, "classes.json")
OUT = os.path.join(HERE, "NON_UNIQUE_CLASSES.md")
TIERS = ("solved", "harder", "open")
RESOLVERS = {"D", "A", "H", "D→A", "D→H", "A→H"}


def load():
    with open(DATA, encoding="utf-8") as f:
        return json.load(f)


def all_classes(data):
    return [c for fam in data["families"] for c in fam["classes"]]


def consistency_errors(data):
    errs = []
    classes = all_classes(data)
    ids = [c["id"] for c in classes]
    if len(ids) != len(set(ids)):
        errs.append("duplicate class IDs")
    known = set(ids)
    for c in classes:
        if c["tier"] not in TIERS:
            errs.append(f"{c['id']}: bad tier {c['tier']}")
        if c["resolver"] not in RESOLVERS:
            errs.append(f"{c['id']}: bad resolver {c['resolver']}")
        for s in c["sources"]:
            if str(s) not in data["sources"]:
                errs.append(f"{c['id']}: unknown source [{s}]")
    by_id = {c["id"]: c for c in classes}
    for p in data["panel_picks"]:
        for cid in p["classes"]:
            if cid not in known:
                errs.append(f"{p['id']}: unknown class {cid}")
            elif by_id[cid]["tier"] != p["tier"]:
                errs.append(f"{cid}: tier {by_id[cid]['tier']} disagrees with panel pick {p['id']} ({p['tier']})")
    for r in data["runners_up"]:
        errs += [f"runner-up: unknown class {cid}" for cid in r["classes"] if cid not in known]
    return errs


def cell(text):
    return str(text).replace("|", "\\|").replace("\n", " ")


def render(data):
    classes = all_classes(data)
    pick_of = {cid: p["id"] for p in data["panel_picks"] for cid in p["classes"]}
    runner = {cid for r in data["runners_up"] for cid in r["classes"]}
    counts = {t: sum(1 for c in classes if c["tier"] == t) for t in TIERS}
    lines = [
        "# Non-unique, untrue and non-actionable candidate classes",
        "",
        "<!-- Generated by catalog/build_catalog.py from catalog/classes.json. Edit the JSON, not this file. -->",
        "",
        f"Version {data['version']}. {len(classes)} classes in {len(data['families'])} families, plus "
        f"{len(data['addenda']['classes'])} proposed additions. Tiers: {counts['solved']} solved, "
        f"{counts['harder']} harder, {counts['open']} open.",
        "",
        "Each class is something a testing tool can hand a person that is not a new, true, actionable finding. "
        "The catalog's rule: **a filter may lower a candidate's rank or change where it goes, but only an oracle "
        "may close it.** Every trap below is a way a filter can hide a real finding; every re-test condition is "
        "what turns a label back into a question.",
        "",
        "**How to read a row.**",
        "",
        f"- **Res.** (resolver): {data['legend']['resolver']}",
        f"- **Tier:** {data['legend']['tier']}",
        f"- **Src:** {data['legend']['sources']}",
        "- **(P1) to (P7)** after an ID marks one of the seven panel picks; **(R)** marks a runner-up.",
        "",
        "## The seven panel picks (ordered from solved to open)",
        "",
        "| Pick | Name | Tier | Classes | Note |",
        "|---|---|---|---|---|",
    ]
    for p in data["panel_picks"]:
        lines.append(f"| {p['id']} | {cell(p['name'])} | {p['tier']} | {', '.join(p['classes'])} | {cell(p['note'])} |")
    lines += ["", "**Runners-up:** " + "; ".join(f"{r['name']} ({', '.join(r['classes'])})" for r in data["runners_up"]) + ".", ""]
    for fam in data["families"]:
        lines += [f"## Family {fam['key']}. {fam['title']}", "",
                  "| ID | Class | Signal | Res. | Tier | Trap (how a filter hides a real finding) | Re-test when / how | Src |",
                  "|---|---|---|---|---|---|---|---|"]
        for c in fam["classes"]:
            tag = f" ({pick_of[c['id']]})" if c["id"] in pick_of else (" (R)" if c["id"] in runner else "")
            src = ", ".join(f"[{s}]" for s in c["sources"]) or "-"
            lines.append(f"| {c['id']}{tag} | {cell(c['name'])} | {cell(c['signal'])} | {c['resolver']} | {c['tier']} | "
                         f"{cell(c['trap'])} | {cell(c['retest'])} | {src} |")
        lines.append("")
    add = data["addenda"]
    lines += [f"## {add['title']}", "",
              "| ID | Class | Signal | Res. | Tier | Trap | Re-test when / how | Related |",
              "|---|---|---|---|---|---|---|---|"]
    for c in add["classes"]:
        lines.append(f"| {c['id']} | {cell(c['name'])} | {cell(c['signal'])} | {c['resolver']} | {c['tier']} | "
                     f"{cell(c['trap'])} | {cell(c['retest'])} | {', '.join(c['related'])} |")
    cited = sorted({str(s) for c in classes for s in c["sources"]}, key=int)
    unsourced = sum(1 for c in classes if not c["sources"])
    lines += ["", "## Sources", "",
              "Every source below was opened on 2026-11-08 and checked against the signal, trap and re-test text "
              "of each class that cites it. Keys a page did not support were removed, and a few pages were "
              "replaced with the primary or current page for the same point; catalog/CATALOG_SOURCE_CHECK.md "
              "records each decision. Most pages were downloaded and searched for the supporting wording; the "
              "pages that refused direct download were read through a fetch tool that returns quoted excerpts. "
              "Key numbers follow the research note the catalog was built from, so gaps mark dropped sources. "
              f"{len(cited)} sources are cited; {unsourced} of {len(classes)} classes rest on reasoning alone "
              "(Src -).", ""]
    for k in sorted(data["sources"], key=int):
        title, url = data["sources"][k]
        lines.append(f"{k}. {title}. <{url}>")
    lines.append("")
    return "\n".join(lines)


def main(argv):
    data = load()
    errs = consistency_errors(data)
    if errs:
        print("catalog data errors:\n  " + "\n  ".join(errs))
        return 1
    text = render(data)
    if "--check" in argv:
        current = ""
        if os.path.exists(OUT):
            with open(OUT, encoding="utf-8") as f:
                current = f.read()
        if current != text:
            print("NON_UNIQUE_CLASSES.md is stale; run catalog/build_catalog.py")
            return 1
        print(f"catalog OK: {len(all_classes(data))} classes")
        return 0
    with open(OUT, "w", encoding="utf-8") as f:
        f.write(text)
    print(f"wrote {OUT} ({len(all_classes(data))} classes)")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
